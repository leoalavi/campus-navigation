#!/usr/bin/env bash
# Build the Campus Navigation web app and deploy it to Cloudflare Workers.
#
#   CAMPUS_NAV_PUBLIC_RELEASE_APPROVED=yes ./scripts/deploy_web.sh  # build + deploy
#   ./scripts/deploy_web.sh --build    # build only (no deploy)
#
# Reads .env (never printed):
#   SUPABASE_URL, SUPABASE_ANON_KEY  required: release builds have no fallback
#   GOOGLE_MAPS_WEB_API_KEY          optional; falls back to GOOGLE_MAPS_API_KEY.
#                                    Shipped to every visitor's browser, so it
#                                    MUST be HTTP-referrer restricted to the
#                                    web app's domain in Google Cloud Console.
# Requires `npx wrangler login` (or CLOUDFLARE_API_TOKEN) for the deploy step.
set -euo pipefail
cd "$(dirname "$0")/.."

ENV_FILE=".env"
[[ -f "$ENV_FILE" ]] || { echo "Error: $ENV_FILE not found."; exit 1; }

read_env() {
  grep "^$1=" "$ENV_FILE" | head -1 | cut -d= -f2- \
    | sed -e 's/^"//' -e 's/"$//' -e "s/^'//" -e "s/'$//" || true
}

SUPABASE_URL="$(read_env SUPABASE_URL)"
SUPABASE_ANON_KEY="$(read_env SUPABASE_ANON_KEY)"
WEB_MAPS_KEY="$(read_env GOOGLE_MAPS_WEB_API_KEY)"
WEB_MAPS_KEY="${WEB_MAPS_KEY:-$(read_env GOOGLE_MAPS_API_KEY)}"

if [[ -z "$SUPABASE_URL" || -z "$SUPABASE_ANON_KEY" ]]; then
  echo "Error: add SUPABASE_URL and SUPABASE_ANON_KEY to $ENV_FILE (the same public values Syllabus Sync uses)."
  exit 1
fi

if [[ -n "$WEB_MAPS_KEY" ]]; then
  printf '// Auto-generated by scripts/deploy_web.sh, do NOT commit this file.\nwindow.GOOGLE_MAPS_API_KEY = "%s";\n' "$WEB_MAPS_KEY" > web/google_maps_config.js
  echo "  ✔ Web Maps key set (must be referrer-restricted)"
else
  printf '// No web Maps key: the app uses the OpenStreetMap fallback.\n' > web/google_maps_config.js
  echo "  ⚠ No web Maps key: Google Maps tab falls back to OpenStreetMap"
fi

flutter build web --release \
  --dart-define=SUPABASE_URL="$SUPABASE_URL" \
  --dart-define=SUPABASE_ANON_KEY="$SUPABASE_ANON_KEY" \
  --dart-define=GOOGLE_MAPS_API_KEY="$WEB_MAPS_KEY" \
  --dart-define=APP_ENV=production

[[ "${1:-}" == "--build" ]] && { echo "Built build/web (not deployed)."; exit 0; }

# Public release is on hold until the University clarifies permissions for the
# campus map, crest, branding and data (meeting 30 Nov 2026). Deploying needs
# an explicit, deliberate opt-in.
if [[ "${CAMPUS_NAV_PUBLIC_RELEASE_APPROVED:-}" != "yes" ]]; then
  echo "Not deploying: public release not approved."
  echo "Built build/web only. Set CAMPUS_NAV_PUBLIC_RELEASE_APPROVED=yes once it is."
  exit 0
fi

npx --yes wrangler@4.163.0 deploy
